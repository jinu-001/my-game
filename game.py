# --- Заголовок ------------------------------------
title = "СОЛЯНЫЕ ШАХТЫ"
frame = "=" * 19
print(frame)
print(" " + title + " ")
print(frame)

# --- Настройка героя -------------------------------
print("Введите начальные характеристики героя.")
health = int(input("Здоровье: "))
strength = int(input("Сила: "))
agility = int(input("Ловкость: "))
endurance = int(input("Выносливость: "))
stamina = int(input("Запас сил: "))
print()

# --- Расчёт базового урона -------------------------
base_attack = 10
damage = base_attack + strength * 1.5
crit_damage = damage * 2

# --- Знакомство с героем --------------------------
print("Как зовут героя?")
hero_name = input()
print(f"Добро пожаловать, {hero_name}!")
print("Ты входишь в подземелье. Здесь темно и пахнет сыростью.")
print()

# --- Меню действий ---------------------------------
print("Что делаешь?")
print("1 - осмотреться")
print("2 - идти вперёд")
print("3 - отдохнуть")
print("4 - прислушаться")
print("5 - зажечь факел")
print("6 - тренировка")
print()

# --- Выбор героя -----------------------------------
choice = input("Выберите действие: ")

# --- Обработка действий ----------------------------
match choice:
    case "1":
        print("Вы осмотрелись. Комната пуста, только пыль на полу.")
    case "2":
        stamina = stamina - 2
        print("Вы осторожно идёте вперёд. Пол скрипит под ногами.")
    case "3":
        stamina = stamina + 1
        print("Вы присели отдохнуть. Усталость постепенно уходит.")
    case "4":
        print("Вы замерли и прислушались. Где-то вдалеке капает вода, опасности не слышно.")
    case "5":
        stamina = stamina - 1
        print("Вы чиркнули кресалом и зажгли факел. Тратится энергия, но стало гораздо светлее.")
    case "6":
        # Блок 1. Инициализация и настройки подземелья
        strikes = 6  # Число кратно 3, чтобы критических ударов было ровно треть
        print("Вы подходите к массивной глыбе соли, испещрённой старыми сколами.")
        print("Предыдущие рабочие использовали её для проверки остроты кирок и своей силы.")
        print()
        print(f"Наносите серию из {strikes} ударов.")
        
        # Блок 2. Накопители (объявляются строго ДО цикла)
        total_damage = 0.0
        crit_count = 0

        # Цикл тренировки
        for i in range(1, strikes + 1):
            # Шаг 1: Определение урона (каждый третий удар — критический)
            if i % 3 == 0:
                hit_damage = crit_damage
                crit_marker = " — критический!"
                crit_count += 1
            else:
                hit_damage = damage
                crit_marker = ""
            
            # Шаг 2: Накопление общего урона
            total_damage += hit_damage
            
            # Шаг 3: Печать текущего удара
            print(f"Удар {i}: {hit_damage:.1f} урона{crit_marker}")
        
        # Блок 3. Итог боя (статистика после цикла)
        average_damage = total_damage / strikes
        stamina_cost = 4  # Стоимость тренировки выше, чем обычная ходьба
        stamina = stamina - stamina_cost

        print()  # Пустая строка перед итогом
        print(f"Итог: {strikes} ударов, критических ударов: {crit_count}")
        print(f"Общий нанесённый урон: {total_damage:.1f}")
        print(f"Средний урон за удар: {average_damage:.1f}")
        print(f"Затраты сил на тренировку: {stamina_cost}")
        
    case _:
        print("Такого действия нет.")

# --- Строка состояния героя ------------------------
print()
print(f"[ Состояние героя — Здоровье: {health} | Запас сил: {stamina} ]")

# --- Прощание --------------------------------------
print()
print(frame)
print("    До свидания, " + hero_name + "!    ")
print(frame)